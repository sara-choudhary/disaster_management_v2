from typing import List, Optional
from datetime import datetime
from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session
from app.database import get_db
from app.models import NetworkEvent, Alert
from app.schemas import (
    NetworkEventResponse,
    AlertResponse,
    AlertUpdate,
)

router = APIRouter(tags=["Events & Alerts"])


@router.get("/events", response_model=List[NetworkEventResponse])
def get_events(
    limit: int = Query(100, ge=1, le=500),
    severity: Optional[str] = None,
    event_type: Optional[str] = None,
    run_id: Optional[str] = None,
    db: Session = Depends(get_db),
):
    """Returns forensic timeline of network events ordered by timestamp descending."""
    query = db.query(NetworkEvent)
    if severity:
        query = query.filter(NetworkEvent.severity == severity.lower())
    if event_type:
        query = query.filter(NetworkEvent.event_type == event_type.upper())
    if run_id:
        query = query.filter(NetworkEvent.simulation_run_id == run_id)

    return query.order_by(NetworkEvent.timestamp.desc()).limit(limit).all()


@router.get("/alerts", response_model=List[AlertResponse])
def get_alerts(
    status: Optional[str] = None,
    severity: Optional[str] = None,
    category: Optional[str] = None,
    limit: int = Query(50, ge=1, le=200),
    db: Session = Depends(get_db),
):
    """Returns alerts generated by actual modeled events (link drops, congestion, ACL violations)."""
    query = db.query(Alert)
    if status:
        query = query.filter(Alert.status == status.lower())
    if severity:
        query = query.filter(Alert.severity == severity.lower())
    if category:
        query = query.filter(Alert.category == category.lower())

    return query.order_by(Alert.timestamp.desc()).limit(limit).all()


@router.patch("/alerts/{alert_id}", response_model=AlertResponse)
def update_alert_status(
    alert_id: str, payload: AlertUpdate, db: Session = Depends(get_db)
):
    """Acknowledges or resolves an alert."""
    alert = db.query(Alert).filter(Alert.alert_id == alert_id).first()
    if not alert:
        raise HTTPException(status_code=404, detail=f"Alert '{alert_id}' not found.")

    alert.status = payload.status
    if payload.status == "resolved":
        alert.resolved_at = datetime.utcnow()

    db.commit()
    db.refresh(alert)
    return alert
